// Counties in each Texas judicial district (Government Code chapter 24), court of appeals district
// (section 22.201), judicial-district attorney (chapter 43), and multicounty court at law (chapter 25),
// for the address guide. Writes src/txJudicialDistricts.js, src/txAppealsDistricts.js, and
// src/txLocalJudicialOffices.js. Run with `npm run data:tx-judicial`.
import { readFile, writeFile } from 'node:fs/promises';
import { ALL_COUNTIES, appealsDistrictKey, parseAppealsDistricts } from './lib/appealsDistricts.mjs';
import { judicialDistrictKey, parseJudicialDistricts } from './lib/judicialDistricts.mjs';
import { districtAttorneyKey, multicountyCourtKey, parseDistrictAttorney, parseMulticountyCourts } from './lib/localJudicialOffices.mjs';

const SOURCE = 'https://tcss.legis.texas.gov/resources/GV/htm/GV.24.htm';
const READABLE = 'https://statutes.capitol.texas.gov/Docs/GV/htm/GV.24.htm';
const countyKey = (name) => (name || '').toLowerCase().replace(/ county$/, '').replace(/[^a-z]/g, '');

const APPEALS_SOURCE = 'https://tcss.legis.texas.gov/resources/GV/htm/GV.22.htm';
const APPEALS_READABLE = 'https://statutes.capitol.texas.gov/Docs/GV/htm/GV.22.htm#22.201';
const fetchText = async (url) => {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return res.text();
};
const DA_SOURCE = 'https://tcss.legis.texas.gov/resources/GV/htm/GV.43.htm';
const DA_READABLE = 'https://statutes.capitol.texas.gov/Docs/GV/htm/GV.43.htm';
const COURTS_SOURCE = 'https://tcss.legis.texas.gov/resources/GV/htm/GV.25.htm';
const COURTS_READABLE = 'https://statutes.capitol.texas.gov/Docs/GV/htm/GV.25.htm#D';
const retrieved = new Date().toISOString().slice(0, 10);

const { districts, skipped } = parseJudicialDistricts(await fetchText(SOURCE));
for (const s of skipped) console.log(`Skipped ${s.key} (Sec. ${s.section}): ${s.reason}`);

// Every county must be a real Texas county, and every District Judge race on the ballot must map.
const data = JSON.parse(await readFile('public/data/tx.json', 'utf8'));
const counties = new Set(data.races.filter((r) => r.county).map((r) => countyKey(r.county)));
if (counties.size !== 254) throw new Error(`Expected 254 counties in tx.json, found ${counties.size}`);
for (const [key, d] of Object.entries(districts)) {
  const unknown = d.counties.filter((c) => !counties.has(countyKey(c)));
  if (unknown.length) throw new Error(`District ${key} (Sec. ${d.section}) has unknown counties: ${unknown}`);
}
const races = data.races.filter((r) => r.category === 'judicial' && r.office.startsWith('District Judge'));
const unmapped = races.filter((r) => !districts[judicialDistrictKey(r.office)]);
if (unmapped.length) throw new Error(`Unmapped races: ${unmapped.map((r) => r.office).join('; ')}`);

const entries = Object.entries(districts)
  .sort(([a], [b]) => parseInt(a, 10) - parseInt(b, 10) || a.localeCompare(b))
  .map(([key, d]) => `  '${key}': ${JSON.stringify(d.counties)}, // Sec. ${d.section}`);
await writeFile('src/txJudicialDistricts.js', `// Generated by scripts/fetch-tx-judicial-districts.mjs. Don't hand-edit.
// Counties in each Texas judicial district (district courts), Government Code chapter 24.
// Source: ${READABLE}
// Retrieved ${retrieved}. Sections not yet in effect are excluded.
export const TX_JUDICIAL_DISTRICTS = {
${entries.join('\n')}
};
`);
console.log(`Wrote ${entries.length} judicial districts; all ${races.length} District Judge races map.`);

const appeals = parseAppealsDistricts(await fetchText(APPEALS_SOURCE));
for (const [key, list] of Object.entries(appeals)) {
  const unknown = list === ALL_COUNTIES ? [] : list.filter((c) => !counties.has(countyKey(c)));
  if (unknown.length) throw new Error(`Court of appeals district ${key} has unknown counties: ${unknown}`);
}
// Section 22.201 assigns every county to a regional court (the 15th is statewide on top of that).
const regional = new Set(Object.values(appeals).filter((l) => l !== ALL_COUNTIES).flat().map(countyKey));
if (regional.size !== counties.size) throw new Error(`Regional courts of appeals cover ${regional.size} of ${counties.size} counties`);
const appealsRaces = data.races.filter((r) => r.category === 'judicial' && /Court of Appeals District/.test(r.office));
const unmappedAppeals = appealsRaces.filter((r) => !appeals[appealsDistrictKey(r.office)]);
if (unmappedAppeals.length) throw new Error(`Unmapped races: ${unmappedAppeals.map((r) => r.office).join('; ')}`);

await writeFile('src/txAppealsDistricts.js', `// Generated by scripts/fetch-tx-judicial-districts.mjs. Don't hand-edit.
// Counties in each Texas court of appeals district, Government Code section 22.201.
// A county can be in two districts (e.g. Hunt is in the 5th and 6th); its voters vote in both.
// ${JSON.stringify(ALL_COUNTIES)} means every county in the state.
// Source: ${APPEALS_READABLE}
// Retrieved ${retrieved}.
export const TX_APPEALS_DISTRICTS = {
${Object.entries(appeals).map(([key, list]) => `  '${key}': ${JSON.stringify(list)},`).join('\n')}
};
`);
console.log(`Wrote ${Object.keys(appeals).length} court of appeals districts; all ${appealsRaces.length} appeals races map.`);

// District attorneys on the ballot: each is elected by its whole judicial district or by named counties.
const daHtml = await fetchText(DA_SOURCE);
const daRaces = data.races.filter((r) => r.category === 'judicial' && r.office.startsWith('District Attorney,'));
const attorneys = {};
for (const race of daRaces) {
  const key = districtAttorneyKey(race.office);
  if (!key) throw new Error(`Unrecognized office: ${race.office}`);
  const parsed = parseDistrictAttorney(daHtml, key);
  const list = parsed.counties ?? districts[parsed.judicialDistrict]?.counties;
  if (!list) throw new Error(`Sec. ${parsed.section}: judicial district ${parsed.judicialDistrict} not in chapter 24`);
  attorneys[key] = { section: parsed.section, counties: list };
}
const courts = parseMulticountyCourts(await fetchText(COURTS_SOURCE));
const courtRaces = data.races.filter((r) => /Multicounty Court at Law/.test(r.office));
const unmappedCourts = courtRaces.filter((r) => !courts[multicountyCourtKey(r.office)]);
if (unmappedCourts.length) throw new Error(`Unmapped races: ${unmappedCourts.map((r) => r.office).join('; ')}`);
for (const [what, table] of [['District attorney', attorneys], ['Multicounty court', courts]]) {
  for (const [key, d] of Object.entries(table)) {
    const unknown = d.counties.filter((c) => !counties.has(countyKey(c)));
    if (unknown.length) throw new Error(`${what} ${key} (Sec. ${d.section}) has unknown counties: ${unknown}`);
  }
}
const rows = (table) => Object.entries(table)
  .sort(([a], [b]) => Number(a) - Number(b))
  .map(([key, d]) => `  '${key}': ${JSON.stringify(d.counties)}, // Sec. ${d.section}`).join('\n');
await writeFile('src/txLocalJudicialOffices.js', `// Generated by scripts/fetch-tx-judicial-districts.mjs. Don't hand-edit.
// Retrieved ${retrieved}.

// Counties whose voters elect each judicial-district attorney on the ballot, Government Code chapter 43.
// "The voters of the Nth Judicial District" uses that district's chapter 24 counties.
// Source: ${DA_READABLE}
export const TX_DISTRICT_ATTORNEYS = {
${rows(attorneys)}
};

// Counties composing each multicounty statutory county court, Government Code chapter 25, subchapter D.
// Source: ${COURTS_READABLE}
export const TX_MULTICOUNTY_COURTS = {
${rows(courts)}
};
`);
console.log(`Wrote ${daRaces.length} district attorneys and ${Object.keys(courts).length} multicounty courts; all ${courtRaces.length} multicounty court races map.`);
